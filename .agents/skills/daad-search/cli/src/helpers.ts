export function writeError(error: string, code: string): void {
  process.stderr.write(JSON.stringify({ error, code }) + "\n")
}

const UA = "Mozilla/5.0 (compatible; daad-cli/1.0)"

export const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms))

/** Pause between requests and before a retry, from DAAD_DELAY_MS (default 2000; tests set 0). */
export function delayMs(): number {
  const raw = process.env.DAAD_DELAY_MS
  const v = raw === undefined || raw.trim() === "" ? NaN : Number(raw)
  return Number.isFinite(v) && v >= 0 ? v : 2000
}

/**
 * Fetch a text body (HTML or JSON), retrying once after a short backoff on a
 * network error (including the 20 s timeout), a 429 or a 5xx. Returns null on a 404.
 */
export async function fetchText(url: string, accept: string): Promise<string | null> {
  for (let attempt = 1; ; attempt++) {
    let response: Response | null = null
    let failure: Error
    try {
      response = await fetch(url, {
        headers: { "User-Agent": UA, Accept: accept },
        redirect: "follow",
        signal: AbortSignal.timeout(20000),
      })
    } catch (e) {
      // Network error or timeout: retryable.
      failure = e instanceof Error ? e : new Error(String(e))
    }
    if (response) {
      if (response.status === 404) return null
      if (response.ok) return response.text()
      failure = new Error(`Request failed: ${response.status} ${response.statusText}`)
      if (response.status !== 429 && response.status < 500) throw failure
    }
    if (attempt === 2) throw failure!
    const base = delayMs()
    await sleep(base + (base ? Math.floor(Math.random() * 500) : 0))
  }
}

